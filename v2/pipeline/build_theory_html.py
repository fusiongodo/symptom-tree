SRC, OUT = sys.argv[1:3]
md = open(SRC, encoding="utf-8").read()


def gfm_lists(text):
    """THEORY.md is written GitHub-style. Python-Markdown needs a blank line before a list and 4-space nesting."""
    out, in_list, in_code = [], False, False
    item = re.compile(r"^(\s*)(- |\d+\. )")
    for line in text.split("\n"):
        if line.startswith("```"): in_code = not in_code
        if in_code or line.startswith("```"):
            out.append(line); continue
        if item.match(line) and not line.startswith(" "):
            if out and out[-1].strip() and not in_list: out.append("")
            in_list = True
        elif not line.strip():
            in_list = False
        elif in_list and line.startswith(" "):
            n = len(line) - len(line.lstrip(" ")); line = " " * (2 * n) + line.lstrip(" ")
        out.append(line)
    return "\n".join(out)


md = gfm_lists(md)
conv = markdown.Markdown(extensions=["tables", "fenced_code", "toc", "sane_lists"],
                         extension_configs={"toc": {"toc_depth": "2-3"}})
body = conv.convert(md)
